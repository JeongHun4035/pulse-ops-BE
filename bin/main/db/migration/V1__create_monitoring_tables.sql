CREATE TABLE sites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    url VARCHAR(2048) NOT NULL UNIQUE,
    interval_seconds INTEGER NOT NULL CHECK (interval_seconds IN (60, 300, 600)),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    next_check_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_sites_due ON sites(next_check_at, id) WHERE enabled;
CREATE TABLE check_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
    checked_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(10) NOT NULL CHECK (status IN ('UP', 'DOWN')),
    http_status_code INTEGER,
    response_time_ms BIGINT,
    error_message VARCHAR(500)
);
CREATE INDEX idx_results_site_time ON check_results(site_id, checked_at DESC, id DESC);
